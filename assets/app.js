    async function searchDocAnswer(text) {
      try {
        const res = await fetch(API + '/api/doc/search?q=' + encodeURIComponent(text) + '&n=3');
        if (!res.ok) return null;
        const data = await res.json();
        if (!data.ok || !data.results || !data.results.length) return null;
        const top = data.results[0];
        const sec = top.section;
        const conf = top.score >= 8 ? 'high' : (top.score >= 4 ? 'medium' : 'low');
        let out = '**' + sec.heading + '**\n\n' + sec.body;
        out += '\n\n\ud83d\udcc4 *Source: Project Document \u2014 Section ' + sec.id + ' \u2014 "' + sec.heading + '"*  (match confidence: ' + conf + ')';
        if (data.results.length > 1) {
          const alt = data.results.slice(1).map(r=> '\u00a7' + r.section.id + ' ' + r.section.heading).join(' \u2022 ');
          out += '\n\n*Also relevant:* ' + alt;
        }
        return out;
      } catch (err) {
        return null;
      }
    }

