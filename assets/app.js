function setGalStatus(msg, isErr){
  if(!galStatus) return;
  galStatus.className = 'gal-status' + (isErr ? ' err' : msg ? ' ok' : '');
  galStatus.textContent = msg || '';
}

function galCard(item){
  const card = document.createElement('div');
  card.className = 'gal-card';
  const img = document.createElement('img');
  img.loading = 'lazy';
  img.alt = item.caption || 'Heritage photo';
  img.src = API + '/uploads/' + encodeURIComponent(item.filename);
  card.appendChild(img);
  if(item.caption){
    const cap = document.createElement('div');
    cap.className = 'gal-cap';
    cap.textContent = item.caption;
    card.appendChild(cap);
  }
  return card;
}

async function loadGallery(){
  const empty = document.getElementById('galEmpty');
  if(!galGrid) return;
  document.querySelectorAll('.gal-card').forEach(n=>n.remove());
  try{
    const res = await fetch(API + '/api/gallery');
    const items = await res.json();
    let has = false;
    items.forEach(item=>{ galGrid.appendChild(galCard(item)); has = true; });
    if(empty) empty.style.display = has ? 'none' : '';
  }catch(err){
    if(empty) empty.style.display = '';
  }
}

if(galForm){
  galForm.addEventListener('submit', async e=>{
    e.preventDefault();
    const file = galFile && galFile.files[0];
    setGalStatus('');
    if(!file){
      setGalStatus((translations[currentLang]||translations.en).gal_need_img, true);
      return;
    }
    if(!authUser){ requireLogin(); return; }
    const fd = new FormData();
    fd.append('file', file);
    fd.append('caption', (galCaption.value || '').trim());
    const btn = galForm.querySelector('[type=submit]');
    btn.disabled = true;
    try{
      const res = await fetch(API + '/api/gallery', {method:'POST', headers: (authToken?{'Authorization':'Bearer '+authToken}:{}), body: fd});
      if(!res.ok){
        setGalStatus((translations[currentLang]||translations.en).gal_fail, true);
        return;
      }
      galCaption.value = '';
      if(galFile) galFile.value = '';
      setGalStatus((translations[currentLang]||translations.en).gal_sent, false);
      loadGallery();
    }catch(err){
      setGalStatus((translations[currentLang]||translations.en).gal_fail, true);
    }finally{
      btn.disabled = false;
    }
  });
  galPickBtn.addEventListener('click', ()=> galFile.click());
  galFile.addEventListener('change', ()=> setGalStatus(''));
}

