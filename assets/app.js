let lastFocus = null;
function modalFocusables(m){
  return Array.prototype.slice.call(m.querySelectorAll('button:not([hidden]):not([disabled]), [href], input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex="-1"])'));
}
function openModal(id){
  const m = document.getElementById(id);
  if(!m) return;
  lastFocus = document.activeElement;
  m.classList.add('open');
  const fields = m.querySelectorAll('input, select, textarea');
  const focusable = modalFocusables(m);
  const first = fields.length ? fields[0] : (focusable[0] || null);
  if(first && !first.disabled && !first.hidden) first.focus();
  m._trap = e=>{
    if(e.key !== 'Tab') return;
    const els = modalFocusables(m);
    if(!els.length) return;
    const a = els[0], b = els[els.length - 1];
    if(e.shiftKey && (document.activeElement === a || !document.activeElement)){ e.preventDefault(); b.focus(); }
    else if(!e.shiftKey && (document.activeElement === b)){ e.preventDefault(); a.focus(); }
  };
  document.addEventListener('keydown', m._trap);
}
function closeModal(id){
  const m = document.getElementById(id);
  if(!m) return;
  m.classList.remove('open');
  if(m._trap){ document.removeEventListener('keydown', m._trap); delete m._trap; }
  if(lastFocus && lastFocus.focus && document.contains(lastFocus)){ lastFocus.focus(); }
  lastFocus = null;
}

