const worldTimers = {};
let worldAuto = true;
function goWorldSlide(world, i){
  const slides = world.querySelectorAll('.slide');
  const dots = world.querySelectorAll('.slider-dots button');
  const n = slides.length;
  if(!n) return;
  world._idx = (i + n) % n;
  slides.forEach((s,k)=> s.classList.toggle('active', k===world._idx));
  dots.forEach((d,k)=> d.classList.toggle('active', k===world._idx));
}
function makeSlide(fileIdx, cap){
  const slide = document.createElement('figure');
  slide.className = 'slide';
  const img = document.createElement('img');
  img.loading = 'lazy';
  img.alt = cap;
  img.src = WORLD_BASE + encodeURIComponent(WORLD_FILES[fileIdx]);
  slide.appendChild(img);
  const c = document.createElement('figcaption');
  c.className = 'slide-cap';
  c.textContent = cap;
  slide.appendChild(c);
  return slide;
}
function resetWorldTimer(world){
  const cat = world.dataset.cat;
  clearInterval(worldTimers[cat]);
  if(!worldAuto) return;
  worldTimers[cat] = setInterval(()=> goWorldSlide(world, (world._idx||0) + 1), 4200);
}
function buildWorld(world){
  const cat = world.dataset.cat;
  const list = (WORLDS[cat] && WORLDS[cat][currentLang]) || WORLDS[cat].en;
  const track = world.querySelector('[data-track]');
  const dotsBox = world.querySelector('[data-dots]');
  clearInterval(worldTimers[cat]);
  track.innerHTML = '';
  dotsBox.innerHTML = '';
  list.forEach(([fi, cap])=>{
    track.appendChild(makeSlide(parseInt(fi.slice(1)) - 1, cap));
    const d = document.createElement('button');
    d.type = 'button';
    d.setAttribute('aria-label', 'Go to slide');
    dotsBox.appendChild(d);
  });
  world._idx = 0;
  goWorldSlide(world, 0);
  world.querySelectorAll('.slider-dots button').forEach((d,k)=>{
    d.addEventListener('click', ()=>{ goWorldSlide(world, k); resetWorldTimer(world); });
  });
  world.querySelector('.slider-nav.prev').addEventListener('click', ()=>{ goWorldSlide(world, (world._idx||0) - 1); resetWorldTimer(world); });
  world.querySelector('.slider-nav.next').addEventListener('click', ()=>{ goWorldSlide(world, (world._idx||0) + 1); resetWorldTimer(world); });
  const win = world.querySelector('.slider-window');
  let tx = null, ty = null, dx = 0, dy = 0;
  win.addEventListener('touchstart', e=>{ tx = e.touches[0].clientX; ty = e.touches[0].clientY; }, {passive:true});
  win.addEventListener('touchmove', e=>{ if(tx===null) return; dx = e.touches[0].clientX - tx; dy = e.touches[0].clientY - ty; }, {passive:true});
  win.addEventListener('touchend', ()=>{
    if(tx===null) return;
    if(Math.abs(dx) > 46 && Math.abs(dx) > Math.abs(dy)){
      goWorldSlide(world, (world._idx||0) + (dx < 0 ? 1 : -1));
      resetWorldTimer(world);
    }
    tx = ty = dx = dy = null;
  });
  world.addEventListener('mouseenter', ()=>{ worldAuto = false; clearInterval(worldTimers[cat]); });
  world.addEventListener('mouseleave', ()=>{ worldAuto = true; resetWorldTimer(world); });
  resetWorldTimer(world);
}
function renderWorlds(){
  document.querySelectorAll('.world').forEach(world=> buildWorld(world));
}
document.addEventListener('visibilitychange', ()=>{
  if(document.hidden){ Object.keys(worldTimers).forEach(k=> clearInterval(worldTimers[k])); }
  else{ worldAuto = true; document.querySelectorAll('.world').forEach(w=> resetWorldTimer(w)); }
});

