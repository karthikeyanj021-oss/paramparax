/* animated stat counters */
const statNums = document.querySelectorAll('.stat-num');
const statObs = new IntersectionObserver(entries=>{
  entries.forEach(en=>{
    if(!en.isIntersecting) return;
    statObs.unobserve(en.target);
    const el = en.target;
    const target = parseFloat(el.getAttribute('data-target'));
    const suffix = el.getAttribute('data-suffix') || '';
    const dur = 1200;
    const start = performance.now();
    function tick(now){
      const p = Math.min((now-start)/dur, 1);
      const eased = 1 - Math.pow(1-p, 3);
      const val = target*eased;
      el.textContent = (target%1===0 ? Math.round(val).toLocaleString('en-IN') : val.toFixed(1)) + suffix;
      if(p<1) requestAnimationFrame(tick);
    }
    requestAnimationFrame(tick);
  });
}, {threshold:.4});
if(statNums.length) statNums.forEach(n=> statObs.observe(n));

/* ---- 3D tilt on cards & tiles ---- */
(function(){
  if(window.matchMedia && window.matchMedia('(hover:none)').matches) return;
  if(window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  const tiltEls = document.querySelectorAll('.card, .gal-card, .contact-card');
  if(!tiltEls.length) return;
  const STRENGTH = 7;
  tiltEls.forEach(el=>{
    el.classList.add('tilt-ready');
    el.addEventListener('mousemove', e=>{
      const r = el.getBoundingClientRect();
      const px = (e.clientX - r.left) / r.width;
      const py = (e.clientY - r.top) / r.height;
      const rx = (0.5 - py) * STRENGTH;
      const ry = (px - 0.5) * STRENGTH;
      el.style.transform = 'perspective(900px) rotateX(' + rx.toFixed(2) + 'deg) rotateY(' + ry.toFixed(2) + 'deg) translateY(-3px)';
    });
    el.addEventListener('mouseleave', ()=>{ el.style.transform = ''; });
  });
})();

